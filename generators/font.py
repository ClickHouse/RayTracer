# ---- space and punctuation ---------------------------------------------
_PUNCT = {
    ' ': ["...", "...", "...", "...", "...", "...", "..."],
    '!': [".#.", ".#.", ".#.", ".#.", ".#.", "...", ".#."],
    '?': [".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."],
    '.': ["..", "..", "..", "..", "..", "##", "##"],
    ',': ["..", "..", "..", "..", "..", "##", ".#"],
    '-': [".....", ".....", ".....", "#####", ".....", ".....", "....."],
    '+': ["...", "...", ".#.", "###", ".#.", "...", "..."],
    '=': ["....", "....", "####", "....", "####", "....", "...."],
    ':': [".", ".", "#", ".", "#", ".", "."],
    "'": ["#", "#", ".", ".", ".", ".", "."],
    '/': ["....#", "....#", "...#.", "..#..", ".#...", "#....", "#...."],
    '&': [".##..", "#..#.", "#.#..", ".#...", "#.#.#", "#..#.", ".##.#"],
    '#': [".#.#.", ".#.#.", "#####", ".#.#.", "#####", ".#.#.", ".#.#."],
    '@': [".###.", "#...#", "#.###", "#.#.#", "#.###", "#....", ".###."],
}

for _src in (_UPPER, _DIGITS, _PUNCT):
    for _k, _v in _src.items():
        glyphs.setdefault(_k, _v)


def _lookup(ch):
    """Resolve a character to a glyph: exact, then uppercase, then '?'."""
    if ch in glyphs:
        return glyphs[ch]
    up = ch.upper()
    if up in glyphs:
        return glyphs[up]
    return glyphs['?']


def banner(text, gap=1):
    """Lay out `text` as a 7-row bitmap. Returns (rows, width)."""
    rows = ["" for _ in range(ROWS)]
    for ch in text:
        g = _lookup(ch)
        w = max(len(r) for r in g)
        for i in range(ROWS):
            rows[i] += g[i].ljust(w, '.') + ("." * gap)
    if gap and text:
        rows = [r[:-gap] for r in rows]   # strip trailing gap
    width = len(rows[0]) if rows[0] else 0
    return rows, width


if __name__ == "__main__":
    import sys
    word = sys.argv[1] if len(sys.argv) > 1 else "ClickHouse"
    rows, width = banner(word)

    for r in rows:
        print(r.replace('.', ' ').replace('#', '@'))
    print()
    print("width:", width)
    print("spheres:", sum(r.count('#') for r in rows))
    print()
    print("[")
    for r in rows:
        print("  '" + r + "',")
    print("]")
