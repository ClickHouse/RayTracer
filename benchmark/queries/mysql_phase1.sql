SET SESSION cte_max_recursion_depth = 100000;

DROP FUNCTION IF EXISTS va; DROP FUNCTION IF EXISTS vs; DROP FUNCTION IF EXISTS vm;
DROP FUNCTION IF EXISTS vd; DROP FUNCTION IF EXISTS vmul; DROP FUNCTION IF EXISTS vn;
DROP FUNCTION IF EXISTS mix; DROP FUNCTION IF EXISTS lerpS; DROP FUNCTION IF EXISTS clampS;
DROP FUNCTION IF EXISTS satb; DROP FUNCTION IF EXISTS hashf; DROP FUNCTION IF EXISTS fade;
DROP FUNCTION IF EXISTS vnoise; DROP FUNCTION IF EXISTS fbm; DROP FUNCTION IF EXISTS terrH;
DROP FUNCTION IF EXISTS terrN; DROP FUNCTION IF EXISTS terrCol; DROP FUNCTION IF EXISTS sky;

CREATE FUNCTION va(a JSON,b JSON) RETURNS JSON DETERMINISTIC RETURN JSON_ARRAY(JSON_VALUE(a,'$[0]' RETURNING DOUBLE)+JSON_VALUE(b,'$[0]' RETURNING DOUBLE), JSON_VALUE(a,'$[1]' RETURNING DOUBLE)+JSON_VALUE(b,'$[1]' RETURNING DOUBLE), JSON_VALUE(a,'$[2]' RETURNING DOUBLE)+JSON_VALUE(b,'$[2]' RETURNING DOUBLE));
CREATE FUNCTION vs(a JSON,b JSON) RETURNS JSON DETERMINISTIC RETURN JSON_ARRAY(JSON_VALUE(a,'$[0]' RETURNING DOUBLE)-JSON_VALUE(b,'$[0]' RETURNING DOUBLE), JSON_VALUE(a,'$[1]' RETURNING DOUBLE)-JSON_VALUE(b,'$[1]' RETURNING DOUBLE), JSON_VALUE(a,'$[2]' RETURNING DOUBLE)-JSON_VALUE(b,'$[2]' RETURNING DOUBLE));
CREATE FUNCTION vm(a JSON,s DOUBLE) RETURNS JSON DETERMINISTIC RETURN JSON_ARRAY(JSON_VALUE(a,'$[0]' RETURNING DOUBLE)*s, JSON_VALUE(a,'$[1]' RETURNING DOUBLE)*s, JSON_VALUE(a,'$[2]' RETURNING DOUBLE)*s);
CREATE FUNCTION vd(a JSON,b JSON) RETURNS DOUBLE DETERMINISTIC RETURN JSON_VALUE(a,'$[0]' RETURNING DOUBLE)*JSON_VALUE(b,'$[0]' RETURNING DOUBLE)+JSON_VALUE(a,'$[1]' RETURNING DOUBLE)*JSON_VALUE(b,'$[1]' RETURNING DOUBLE)+JSON_VALUE(a,'$[2]' RETURNING DOUBLE)*JSON_VALUE(b,'$[2]' RETURNING DOUBLE);
CREATE FUNCTION vmul(a JSON,b JSON) RETURNS JSON DETERMINISTIC RETURN JSON_ARRAY(JSON_VALUE(a,'$[0]' RETURNING DOUBLE)*JSON_VALUE(b,'$[0]' RETURNING DOUBLE), JSON_VALUE(a,'$[1]' RETURNING DOUBLE)*JSON_VALUE(b,'$[1]' RETURNING DOUBLE), JSON_VALUE(a,'$[2]' RETURNING DOUBLE)*JSON_VALUE(b,'$[2]' RETURNING DOUBLE));
CREATE FUNCTION vn(a JSON) RETURNS JSON DETERMINISTIC RETURN vm(a, 1.0/sqrt(greatest(vd(a,a),1e-18)));
CREATE FUNCTION mix(a JSON,b JSON,t DOUBLE) RETURNS JSON DETERMINISTIC RETURN va(a, vm(vs(b,a), t));
CREATE FUNCTION lerpS(a DOUBLE,b DOUBLE,t DOUBLE) RETURNS DOUBLE DETERMINISTIC RETURN a*(1.0-t)+b*t;
CREATE FUNCTION clampS(lo DOUBLE,hi DOUBLE,x DOUBLE) RETURNS DOUBLE DETERMINISTIC RETURN greatest(lo, least(hi, x));
CREATE FUNCTION satb(c JSON) RETURNS JSON DETERMINISTIC RETURN mix(JSON_ARRAY(JSON_VALUE(c,'$[0]' RETURNING DOUBLE)*0.30+JSON_VALUE(c,'$[1]' RETURNING DOUBLE)*0.59+JSON_VALUE(c,'$[2]' RETURNING DOUBLE)*0.11, JSON_VALUE(c,'$[0]' RETURNING DOUBLE)*0.30+JSON_VALUE(c,'$[1]' RETURNING DOUBLE)*0.59+JSON_VALUE(c,'$[2]' RETURNING DOUBLE)*0.11, JSON_VALUE(c,'$[0]' RETURNING DOUBLE)*0.30+JSON_VALUE(c,'$[1]' RETURNING DOUBLE)*0.59+JSON_VALUE(c,'$[2]' RETURNING DOUBLE)*0.11), c, 1.45);

CREATE FUNCTION hashf(ix BIGINT,iy BIGINT) RETURNS DOUBLE DETERMINISTIC RETURN ((((((ix+4096)+(iy+4096)*8192)*1103515245+12345)%2147483648)*1103515245+12345)%2147483648%65536)/65536.0;
CREATE FUNCTION fade(t DOUBLE) RETURNS DOUBLE DETERMINISTIC RETURN t*t*t*(t*(t*6.0-15.0)+10.0);
CREATE FUNCTION vnoise(x DOUBLE,y DOUBLE) RETURNS DOUBLE DETERMINISTIC RETURN
  lerpS(lerpS(hashf(floor(x),floor(y)), hashf(floor(x)+1,floor(y)), fade(x-floor(x))),
        lerpS(hashf(floor(x),floor(y)+1), hashf(floor(x)+1,floor(y)+1), fade(x-floor(x))),
        fade(y-floor(y)));
CREATE FUNCTION fbm(x DOUBLE,y DOUBLE) RETURNS DOUBLE DETERMINISTIC RETURN
  (vnoise(x,y)*0.5 + vnoise(x*2.0,y*2.0)*0.25 + vnoise(x*4.0,y*4.0)*0.125 + vnoise(x*8.0,y*8.0)*0.0625)/0.9375;
CREATE FUNCTION terrH(x DOUBLE,y DOUBLE) RETURNS DOUBLE DETERMINISTIC RETURN 2.4*(fbm(x*0.05,y*0.05)-0.5);
CREATE FUNCTION terrN(x DOUBLE,y DOUBLE) RETURNS JSON DETERMINISTIC RETURN vn(JSON_ARRAY((terrH(x-0.25,y)-terrH(x+0.25,y))/0.5, (terrH(x,y-0.25)-terrH(x,y+0.25))/0.5, 1.0));
CREATE FUNCTION terrCol(h DOUBLE) RETURNS JSON DETERMINISTIC RETURN
  mix(mix(mix(mix(JSON_ARRAY(0.06,0.24,0.55), JSON_ARRAY(0.84,0.68,0.32), clampS(0.0,1.0,(h+0.6)/0.4)),
                  JSON_ARRAY(0.16,0.52,0.09), clampS(0.0,1.0,(h+0.1)/0.5)),
              JSON_ARRAY(0.46,0.32,0.22), clampS(0.0,1.0,(h-0.6)/0.4)),
          JSON_ARRAY(0.97,0.98,1.0), clampS(0.0,1.0,(h-1.0)/0.3));
CREATE FUNCTION sky(d JSON) RETURNS JSON DETERMINISTIC RETURN mix(JSON_ARRAY(0.66,0.78,0.96), JSON_ARRAY(0.30,0.50,0.85), greatest(0.0, least(1.0, JSON_VALUE(d,'$[2]' RETURNING DOUBLE)*1.5)));

WITH RECURSIVE
seq(i) AS (SELECT 0 UNION ALL SELECT i+1 FROM seq WHERE i < 511),
px AS (
  SELECT i AS idx,
         CAST(JSON_ARRAY(24.0,-45.0,12.0) AS JSON) AS o,
         vn(va(CAST(JSON_ARRAY(0.0,0.9912279,-0.13216372) AS JSON),
                va(vm(CAST(JSON_ARRAY(1.0,-0.0,0.0) AS JSON), (((i % 32) + 0.5)/32.0*2.0-1.0)*2.0*0.3249197),
                   vm(CAST(JSON_ARRAY(0.0,0.13216372,0.9912279) AS JSON), (1.0 - (FLOOR(i/32)+0.5)/16.0*2.0)*0.3249197)))) AS d
  FROM seq
),
m AS (
  SELECT idx, o, d,
         CASE WHEN JSON_VALUE(d,'$[2]' RETURNING DOUBLE) < -0.001 THEN greatest(0.05, (JSON_VALUE(o,'$[2]' RETURNING DOUBLE)-1.55)/(-JSON_VALUE(d,'$[2]' RETURNING DOUBLE))) ELSE 0.05 END AS t,
         CAST(0.0 AS DOUBLE) AS prevT, CAST(1e9 AS DOUBLE) AS prevDiff,
         CAST(1e9 AS DOUBLE) AS result, 0 AS done, 0 AS iter
  FROM px
  UNION ALL
  SELECT idx, o, d,
    CASE WHEN prevDiff>0.0 AND (JSON_VALUE(o,'$[2]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[2]' RETURNING DOUBLE)-terrH(JSON_VALUE(o,'$[0]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[0]' RETURNING DOUBLE),JSON_VALUE(o,'$[1]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[1]' RETURNING DOUBLE)))<=0.0 THEN t ELSE t+greatest(0.06,t*0.035) END,
    t,
    (JSON_VALUE(o,'$[2]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[2]' RETURNING DOUBLE)-terrH(JSON_VALUE(o,'$[0]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[0]' RETURNING DOUBLE),JSON_VALUE(o,'$[1]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[1]' RETURNING DOUBLE))),
    CASE WHEN prevDiff>0.0 AND (JSON_VALUE(o,'$[2]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[2]' RETURNING DOUBLE)-terrH(JSON_VALUE(o,'$[0]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[0]' RETURNING DOUBLE),JSON_VALUE(o,'$[1]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[1]' RETURNING DOUBLE)))<=0.0
              THEN prevT + (t-prevT)*prevDiff/(prevDiff-(JSON_VALUE(o,'$[2]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[2]' RETURNING DOUBLE)-terrH(JSON_VALUE(o,'$[0]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[0]' RETURNING DOUBLE),JSON_VALUE(o,'$[1]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[1]' RETURNING DOUBLE)))) ELSE 1e9 END,
    CASE WHEN prevDiff>0.0 AND (JSON_VALUE(o,'$[2]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[2]' RETURNING DOUBLE)-terrH(JSON_VALUE(o,'$[0]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[0]' RETURNING DOUBLE),JSON_VALUE(o,'$[1]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[1]' RETURNING DOUBLE)))<=0.0 THEN 1
         WHEN JSON_VALUE(o,'$[2]' RETURNING DOUBLE)+t*JSON_VALUE(d,'$[2]' RETURNING DOUBLE) > 1.55 AND JSON_VALUE(d,'$[2]' RETURNING DOUBLE)>=0.0 THEN 2 ELSE 0 END,
    iter+1
  FROM m WHERE done=0 AND iter<110
),
terr AS (SELECT idx, MIN(CASE WHEN done=1 THEN result ELSE 1e9 END) AS tTerr FROM m GROUP BY idx),
hit AS (
  SELECT p.idx, p.o, p.d, t.tTerr, va(p.o, vm(p.d, least(t.tTerr,5000.0))) AS hp
  FROM px p JOIN terr t ON p.idx=t.idx
),
shade AS (
  SELECT idx,
    mix(satb(vmul(terrCol(JSON_VALUE(hp,'$[2]' RETURNING DOUBLE)),
                  va(vm(CAST(JSON_ARRAY(0.45,0.56,0.80) AS JSON), 0.26+0.18*greatest(JSON_VALUE(terrN(JSON_VALUE(hp,'$[0]' RETURNING DOUBLE),JSON_VALUE(hp,'$[1]' RETURNING DOUBLE)),'$[2]' RETURNING DOUBLE),0.0)),
                     vm(CAST(JSON_ARRAY(1.06,0.97,0.82) AS JSON),
                        1.45*greatest(vd(vn(vs(CAST(JSON_ARRAY(9.0,-30.0,52.0) AS JSON), hp)), terrN(JSON_VALUE(hp,'$[0]' RETURNING DOUBLE),JSON_VALUE(hp,'$[1]' RETURNING DOUBLE))),0.0))))),
        sky(d),
        CASE WHEN tTerr>1e8 THEN 1.0 ELSE 0.0 END) AS col
  FROM hit
)
SELECT idx,
  CAST(ROUND(clampS(0.0,1.0, POWER(greatest(JSON_VALUE(col,'$[0]' RETURNING DOUBLE),0.0)*1.15, 1.0/2.2))*255) AS SIGNED) AS r,
  CAST(ROUND(clampS(0.0,1.0, POWER(greatest(JSON_VALUE(col,'$[1]' RETURNING DOUBLE),0.0)*1.15, 1.0/2.2))*255) AS SIGNED) AS g,
  CAST(ROUND(clampS(0.0,1.0, POWER(greatest(JSON_VALUE(col,'$[2]' RETURNING DOUBLE),0.0)*1.15, 1.0/2.2))*255) AS SIGNED) AS b
FROM shade ORDER BY idx;
